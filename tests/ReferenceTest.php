<?php

namespace Cabuz\Stedi\Tests;

use Cabuz\Stedi\Stedi;
use Cabuz\Stedi\Tests\Concerns\WalksOperations;
use Illuminate\Support\Facades\Http;
use ReflectionClass;
use ReflectionMethod;
use ReflectionNamedType;

/**
 * Keeps api.md and the facade's @method docblock in sync with the code.
 * Regenerate both with bin/generate (UPDATE_REFERENCE=1).
 */
class ReferenceTest extends TestCase
{
    use WalksOperations;

    private const TITLES = [
        'Healthcare' => 'Eligibility, claims and remittances',
        'Claims' => 'Claims',
        'EligibilityManager' => 'Batch eligibility (Eligibility Manager)',
        'Payers' => 'Payers',
        'Enrollment' => 'Transaction enrollment',
        'EventDestinations' => 'Event destinations (webhooks)',
        'Core' => 'Core (EDI platform)',
    ];

    public function test_api_md_lists_every_operation(): void
    {
        Http::fake(['*' => Http::response(['items' => [], 'nextPageToken' => null])]);
        $stedi = $this->app->make(Stedi::class);

        $lines = [
            '# API reference',
            '',
            '<!-- Generated by bin/generate from the source code. Do not edit by hand. -->',
            '',
            'Every Stedi operation, as a method on the `Stedi` facade (or an injected `Cabuz\\Stedi\\Stedi`).',
            'Method names are the OpenAPI operation names, like the official [Stedi SDK](https://github.com/Stedi/sdk).',
            'List methods return a `CursorPage`, file downloads the raw contents as a string, the others the',
            'decoded JSON as an array. Field-level documentation is in the [Stedi API reference](https://www.stedi.com/docs).',
        ];

        $groups = $this->operationMethods();
        $groups = array_replace(array_intersect_key(self::TITLES, $groups), $groups);

        foreach ($groups as $group => $methods) {
            $lines[] = '';
            $lines[] = '## '.(self::TITLES[$group] ?? $group);
            $lines[] = '';
            $lines[] = '| Method | Endpoint |';
            $lines[] = '|---|---|';

            foreach ($methods as $method) {
                [$verb, $api, $path] = explode(' ', $this->operationsCalled($stedi, $method)[0], 3);
                $lines[] = '| `'.$this->signature($method).'` | `'.$verb.' '.$path.'` ('.$api.') |';
            }
        }

        $this->assertInSync(__DIR__.'/../api.md', implode("\n", $lines)."\n", 'api.md');
    }

    public function test_the_facade_documents_every_method(): void
    {
        $lines = [];

        foreach ((new ReflectionClass(Stedi::class))->getMethods(ReflectionMethod::IS_PUBLIC) as $method) {
            if ($method->isConstructor() || $method->isStatic()) {
                continue;
            }

            $return = (string) $method->getReturnType();
            $return = match (true) {
                $return === 'array' => 'array<string, mixed>',
                $return === 'static' => 'StediClient',
                default => '\\'.ltrim($return, '?\\').(str_starts_with($return, '?') ? '|null' : ''),
            };
            $return = in_array(ltrim($return, '\\'), ['string', 'mixed', 'void'], true) ? ltrim($return, '\\') : $return;

            $lines[] = ' * @method static '.$return.' '.$this->signature($method, docblock: true);
        }

        $file = __DIR__.'/../src/Facades/Stedi.php';
        $source = (string) file_get_contents($file);
        $expected = (string) preg_replace('#/\*\*\n(?: \* @method .*\n|\s\*\s@generated-methods\n)+ \*\n \* @see#', "/**\n".implode("\n", $lines)."\n *\n * @see", $source, 1);

        $this->assertInSync($file, $expected, 'The facade docblock');
    }

    private function assertInSync(string $file, string $expected, string $what): void
    {
        if (getenv('UPDATE_REFERENCE')) {
            file_put_contents($file, $expected);
        }

        $this->assertSame($expected, (string) @file_get_contents($file), "{$what} is out of date; run bin/generate.");
    }

    private function signature(ReflectionMethod $method, bool $docblock = false): string
    {
        $parameters = array_map(function ($parameter) use ($docblock) {
            $type = $parameter->getType();
            $name = $type instanceof ReflectionNamedType ? $type->getName() : (string) $type;

            $nullable = $type !== null && $type->allowsNull() && $name !== 'mixed';

            if ($docblock && $name === 'array') {
                $text = 'array<string, mixed>'.($nullable ? '|null' : '').' $'.$parameter->getName();
            } else {
                $text = ($type !== null ? ($nullable ? '?' : '').$name.' ' : '').'$'.$parameter->getName();
            }

            if ($parameter->isDefaultValueAvailable()) {
                $default = $parameter->getDefaultValue();
                $text .= ' = '.match (true) {
                    $default === [] => '[]',
                    $default === null => 'null',
                    is_bool($default) => $default ? 'true' : 'false',
                    is_string($default) => "'".$default."'",
                    default => (string) $default,
                };
            }

            return $text;
        }, $method->getParameters());

        $signature = $method->getName().'('.implode(', ', $parameters).')';

        if ($docblock) {
            return $signature;
        }

        $return = (string) $method->getReturnType();

        return $signature.': '.preg_replace('#^(\??).*\\\\#', '$1', $return);
    }
}
